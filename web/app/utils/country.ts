function flagForCode(code: string): string {
  const value = code.toUpperCase()
  if (!/^[A-Z]{2}$/.test(value)) return ''
  return String.fromCodePoint(
    0x1F1E6 + value.charCodeAt(0) - 65,
    0x1F1E6 + value.charCodeAt(1) - 65
  )
}

function countryCode(name: string): string {
  let code = ''
  for (const token of name.split(/[^\p{L}\p{N}]+/u)) {
    const candidate = token.toUpperCase()
    if (countryAliases[candidate]) code = countryAliases[candidate]
  }
  return code
}

function hasFlagEmoji(value: string): boolean {
  for (const char of value) {
    const code = char.codePointAt(0) ?? 0
    if (code >= 0x1F1E6 && code <= 0x1F1FF) return true
  }
  return false
}

function stripLeadingFlags(value: string): string {
  return value.trim().replace(/^(?:[\u{1F1E6}-\u{1F1FF}]\s*)+/u, '')
}

export function countryFlag(name: string): string {
  const value = name.trim()
  if (!value || hasFlagEmoji(value)) return ''
  const code = countryCode(value)
  return code ? flagForCode(code) : ''
}

export function displayName(name: string, country = ''): string {
  const manual = country.trim().toUpperCase()
  if (manual) {
    const flag = flagForCode(manual)
    if (flag) return `${flag} ${stripLeadingFlags(name)}`
  }
  const flag = countryFlag(name)
  return flag ? `${flag} ${name}` : name
}

const regionNames = new Intl.DisplayNames(['zh-CN'], { type: 'region' })

export const countryOptions = (() => {
  const seen = new Set<string>()
  const options: Array<{ label: string; value: string }> = []
  for (const iso of Object.values(countryAliases)) {
    if (seen.has(iso)) continue
    seen.add(iso)
    let name = iso
    try {
      name = regionNames.of(iso) || iso
    } catch {
      // Keep the ISO code when the runtime lacks a display name.
    }
    options.push({ label: `${flagForCode(iso)} ${name} (${iso})`, value: iso })
  }
  options.sort((a, b) => a.label.localeCompare(b.label, 'zh-CN'))
  return [{ label: '自动检测（按名称）', value: 'auto' }, ...options]
})()
